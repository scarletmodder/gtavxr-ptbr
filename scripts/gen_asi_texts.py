"""Generates src/GtavxrPtbrAsi/texts.g.h from translations/vr-menu.pt-BR.json and translations/trainer.pt-BR.json.

The plugin only carries the keys it looks up (the GTAVXR source text of each row) and the Portuguese texts.
Run: python scripts/gen_asi_texts.py
"""
import json
import pathlib

ROOT = pathlib.Path(__file__).resolve().parent.parent
OUT = ROOT / "src" / "GtavxrPtbrAsi" / "texts.g.h"

# In the game the Portuguese texts take the place of the Spanish ones, so the language that used to be called
# Spanish is now Portuguese: its name must say so.
TRAINER_OVERRIDES = {"Spanish": "Português"}


def c_string(text: str) -> str:
    out = []
    for byte in text.encode("utf-8"):
        ch = chr(byte)
        if ch == "\\":
            out.append("\\\\")
        elif ch == '"':
            out.append('\\"')
        elif 32 <= byte < 127:
            out.append(ch)
        else:
            out.append("\\%03o" % byte)
    return '"' + "".join(out) + '"'


def load(name: str, overrides=None):
    rows = json.loads((ROOT / "translations" / name).read_text(encoding="utf-8"))
    seen = {}
    for row in rows:
        key, pt = row["id"], row["pt"]
        if overrides and key in overrides:
            pt = overrides[key]
        if not pt:
            continue
        seen.setdefault(key, pt)
    return seen


def emit(name: str, texts: dict) -> str:
    lines = [f"static const Text {name}[] = {{"]
    for key, pt in texts.items():
        lines.append(f"    {{{c_string(key)}, {c_string(pt)}}},")
    lines.append("};")
    return "\n".join(lines)


def main():
    vr = load("vr-menu.pt-BR.json")
    trainer = load("trainer.pt-BR.json", TRAINER_OVERRIDES)
    body = [
        "// Generated by scripts/gen_asi_texts.py from translations/*.pt-BR.json. Do not edit.",
        "#pragma once",
        '#include "table_patch.h"',
        "namespace gtavxr_ptbr {",
        emit("VrTexts", vr),
        emit("TrainerTexts", trainer),
        f"static const size_t VrTextCount = {len(vr)};",
        f"static const size_t TrainerTextCount = {len(trainer)};",
        "}  // namespace gtavxr_ptbr",
        "",
    ]
    OUT.write_text("\n".join(body), encoding="utf-8", newline="\n")
    print(f"{OUT.relative_to(ROOT)}: VR {len(vr)}, Trainer {len(trainer)}")


if __name__ == "__main__":
    main()
